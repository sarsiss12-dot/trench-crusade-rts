export const LANGUAGES = { tr: TR, en: EN };
let current = 'tr';

export function setLanguage(lang) {
  current = LANGUAGES[lang] ? lang : 'tr';
  return current;
}

export function getLanguage() {
  return current;
}

/** Translate key with {param} substitution. */
export function t(key, params) {
  let s = LANGUAGES[current][key];
  if (s === undefined) s = EN[key];
  if (s === undefined) s = key;
  if (params) s = s.replace(/\{(\w+)\}/g, (m, k) => (params[k] !== undefined ? String(params[k]) : m));
  return s;
}

/** mm:ss (or h:mm:ss) clock text. */
export function formatClock(seconds) {
  const s = Math.max(0, Math.floor(seconds));
  const h = Math.floor(s / 3600), m = Math.floor((s % 3600) / 60), r = s % 60;
  const mm = (h ? String(m).padStart(2, '0') : String(m)) + ':' + String(r).padStart(2, '0');
  return h ? h + ':' + mm : mm;
}

/** Keys present in Turkish but missing in English and vice versa (for tests). */
export function missingKeys() {
  const tr = Object.keys(TR), en = Object.keys(EN);
  return { inEn: tr.filter((k) => !(k in EN)), inTr: en.filter((k) => !(k in TR)) };
}
